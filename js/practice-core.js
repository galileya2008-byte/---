  function localDateKey(date) {
    var y = date.getFullYear();
    var m = date.getMonth() + 1;
    var d = date.getDate();
    return y + "-" + (m < 10 ? "0" : "") + m + "-" + (d < 10 ? "0" : "") + d;
  }

  function taskIndexForDate(date) {
    if (!(date instanceof Date) || isNaN(date.getTime())) return 0;
    var indexTime = Date.UTC(date.getFullYear(), date.getMonth(), date.getDate());
    var yearStart = Date.UTC(date.getFullYear(), 0, 1);
    var dayOfYear = Math.floor((indexTime - yearStart) / 86400000);
    return ((dayOfYear % 30) + 30) % 30;
  }

